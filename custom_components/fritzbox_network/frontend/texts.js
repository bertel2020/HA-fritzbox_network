export const TEXTS = { en, de };

export function panelTexts(language) {
  return TEXTS[String(language ?? "en").split("-")[0]] ?? en;
}

/** Fills the {name} placeholders of a text. */
export function fill(text, values = {}) {
  return String(text).replace(/\{(\w+)\}/g, (_, key) => values[key] ?? "");
}
